# PlatformIO pre-build step: embeds the shared settings page
# (../software/web/index.html) into the firmware as a gzipped byte array.
# One page for both the Raspberry Pi and the ESP32-C3 versions.
import gzip, os
Import("env")  # noqa: F821  (provided by PlatformIO)

proj = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.normpath(os.path.join(proj, "..", "software", "web", "index.html"))
dst = os.path.join(proj, "src", "web_index.h")
data = gzip.compress(open(src, "rb").read(), 9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
out = ("// Generated by scripts/embed_web.py from software/web/index.html – do not edit.\n"
       "#pragma once\n#include <Arduino.h>\n"
       f"static const size_t INDEX_GZ_LEN = {len(data)};\n"
       "static const uint8_t INDEX_GZ[] PROGMEM = {\n  " + ",\n  ".join(lines) + "\n};\n")
if not os.path.exists(dst) or open(dst).read() != out:
    open(dst, "w").write(out)
print(f"embed_web: {os.path.relpath(src, proj)} -> src/web_index.h ({len(data)} bytes gzipped)")
